const ALIASES: Record<string, string> = {
  fb: "facebook",
  ig: "instagram",
  yt: "youtube",
  twitter: "x",
  gh: "github",
  ln: "linkedin",
  in: "linkedin",
  tt: "tiktok",
  dc: "discord",
  wa: "whatsapp",
  tg: "telegram",
  mail: "email",
  gmail: "email",
  web: "website",
  site: "website",
};

export function resolveBrand(platform: string, icon: string | null = null): Brand {
  const candidates = [icon ?? "", platform ?? ""].map((s) => (s || "").toLowerCase().trim());
  for (const c of candidates) {
    if (!c) continue;
    if (BRANDS[c]) return { key: c, ...BRANDS[c] };
    if (ALIASES[c]) return { key: ALIASES[c], ...BRANDS[ALIASES[c]] };
    for (const key of Object.keys(BRANDS)) if (c.includes(key)) return { key, ...BRANDS[key] };
  }
  return { key: "website", ...BRANDS.website };
}

/** Try to detect platform key from a URL hostname. */
export function detectFromUrl(url: string): string | null {
  try {
    const host = new URL(url).hostname.replace(/^www\./, "").toLowerCase();
    if (host.includes("facebook") || host.includes("fb.com")) return "facebook";
    if (host.includes("instagram")) return "instagram";
    if (host.includes("youtube") || host.includes("youtu.be")) return "youtube";
    if (host.includes("twitter") || host === "x.com" || host.endsWith(".x.com")) return "x";
    if (host.includes("github")) return "github";
    if (host.includes("linkedin")) return "linkedin";
    if (host.includes("tiktok")) return "tiktok";
    if (host.includes("discord")) return "discord";
    if (host.includes("whatsapp") || host.includes("wa.me")) return "whatsapp";
    if (host.includes("t.me") || host.includes("telegram")) return "telegram";
    if (url.startsWith("mailto:")) return "email";
    return "website";
  } catch {
    if (url.startsWith("mailto:")) return "email";
    return null;
  }
}
